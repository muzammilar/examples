CREATE TABLE IF NOT EXISTS customers (
 customer_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL,
 PRIMARY KEY(customer_id)
) ENGINE=NDBCLUSTER PARTITION BY KEY(customer_id) PARTITIONS 3;
CREATE TABLE IF NOT EXISTS orders (
 customer_id BIGINT NOT NULL, op_id BIGINT NOT NULL, amount BIGINT NOT NULL,
 PRIMARY KEY(customer_id,op_id)
) ENGINE=NDBCLUSTER PARTITION BY KEY(customer_id) PARTITIONS 3;
CREATE TABLE IF NOT EXISTS subscribers (
 subscriber_id BIGINT NOT NULL,
 phone BIGINT NOT NULL,
 lookup_ref BIGINT NOT NULL,
 quota BIGINT NOT NULL,
 version INT NOT NULL,
 PRIMARY KEY(subscriber_id),
 UNIQUE KEY phone USING HASH(phone)
) ENGINE=NDBCLUSTER PARTITION BY KEY(subscriber_id) PARTITIONS 3;
